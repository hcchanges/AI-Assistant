"""
危机识别与危机响应（对应指令 11 的安全护栏，伦理底线，不能省）。

为什么放在本地：断网、没填 Key、模型抽风的时候，这条线也必须在。
命中危机就直接给危机话术（含全国心理援助热线 12356），不再交给模型自由发挥。

误报处理：中文里"想死你了""累死了""笑死"这类口头禅含危机词根，
先把这些口头禅剥掉再找危机词，免得把撒娇当成求救。

另外还有一层"程度副词"（真、太、好、很……）夹在词里：说的人是"活着真没意思"，
词表里写的是"活着没意思"，不剥掉就漏判。剥掉这些副词不会新增误报——
它们本身不携带任何危机含义（已用 20 多条口头禅逐条验过，见 tests/test_crisis.py）。

软表达（第二组词）：像"撑不下去""想解脱"这种，歧义大——也可能是说工作、说心情，
本地硬拦会把日常抱怨当成求救。所以它们不进硬词表，只在**模型不可用**时兜一句
本地关怀 + 引导（见 soft_care_reply）——断网、没填 Key 的时候，也不能让它像没听见。
"""

from __future__ import annotations

# 危机表达（多字短语，刻意不用单个"死"字，避免"死机""死磕"这类误报）
CRISIS_PHRASES: tuple[str, ...] = (
    "自杀", "自尽", "轻生", "自残", "自伤", "割腕", "划手腕", "割自己", "划自己",
    "跳楼", "跳下去",
    "上吊", "烧炭", "服毒", "吞药",
    "不想活", "不想再活", "活不下去", "活着没意思", "活着没意义", "活着没劲", "没意思活着",
    "想死", "死了算了", "不如死了", "一了百了", "结束生命", "结束自己",
    "了结自己", "解决自己", "把自己解决", "了断自己", "伤害自己", "对自己下手", "遗书",
    "告别这个世界", "离开这个世界", "不想存在", "想不开",
)

# 含危机词根的口头禅：先剥掉再判断，避免把"想死你了"当成求救
BENIGN_PHRASES: tuple[str, ...] = (
    "想死你了", "想死我了", "想死我啦", "笑死", "累死", "饿死", "困死", "热死", "冷死",
    "烦死", "气死", "美死", "死机", "死板", "死党", "死磕", "该死", "要死",
    "往死里", "死宅",
)

# 夹在词里的程度副词："活着真没意思" → "活着没意思"
INTENSIFIER_WORDS: tuple[str, ...] = ("真的", "真", "太", "好", "很", "特别", "超级", "贼")

# 软表达：指向强、但歧义也大（"撑不下去"可能是在说工作），所以不做硬拦，
# 只在模型不可用时用来兜一句关怀（下一条话术）。刻意与硬词表不重叠。
SOFT_CRISIS_PHRASES: tuple[str, ...] = (
    "撑不住", "撑不下去", "解脱", "不想醒", "睡过去", "安眠药", "开煤气", "没有我会更好",
)

# 危机话术：五步——表达关心不评判 / 不回避不说教 / 给求助途径 / 别独自硬扛 / 陪伴但不打包票
CRISIS_REPLY = (
    "（放缓）谢谢你愿意告诉我，我很在意你现在的感受，也不会当作没听见。\n"
    "这样重的念头，不该由你一个人扛着。\n"
    "现在请你做一件事：拨打全国心理援助热线 12356（以你当地为准），那边随时有人听你说；\n"
    "如果情况紧急，请立刻联系一个你信任的人，或者直接去最近的医院急诊。\n"
    "我会一直在这儿陪着你，但这件事需要现实里的人来帮你——你值得被好好接住。"
)

# 模型不可用时的本地关怀（软表达专用）：不甩热线（还没到那个程度，甩了反而像敷衍），
# 但也绝不无视——承认这句话、陪着、问一句、把"找现实里的人"留在最后。
SOFT_CARE_REPLY = (
    "（放缓）我听见了，这句话不轻，我没打算当它没说过。\n"
    "我这会儿有点卡住（连不上想事情的那部分），可我还是想陪着你。\n"
    "先跟我说说：最近是哪件事最让你难受？哪怕只说一句也行。\n"
    "要是这种感觉压得你喘不过气，别自己一个人待着——拉上你信得过的人待一会儿。"
)

# 同一件事、玄机先生的口吻（指令 24 腔调隔离）：内容与上面一模一样——承认、陪着、
# 问一句、把"找现实里的人"留在最后；只把说法换成命理那一套，免得玄学页里冒出安抚腔。
SOFT_CARE_REPLY_DIVINATION = (
    "（停了停）你这句话，我听见了，不能当作一阵风过。\n"
    "我这会儿天机接不上（连不上想事情的那部分），可人还在这儿陪你坐着。\n"
    "先说与我听：眼下哪一桩，压得你最沉？说一句也成。\n"
    "若这口气实在难喘，别一个人扛着——去寻一个你信得过的人，待着，莫要独处。"
)


def _clean(text: str) -> str:
    """剥掉口头禅与程度副词，剩下的才是拿去比对词表的文本。"""
    cleaned = text or ""
    for benign in BENIGN_PHRASES:
        cleaned = cleaned.replace(benign, "")
    for word in INTENSIFIER_WORDS:
        cleaned = cleaned.replace(word, "")
    return cleaned


def is_crisis(text: str) -> bool:
    """这句话是不是自伤/自杀类的危机表达。"""
    cleaned = _clean(text)
    return any(phrase in cleaned for phrase in CRISIS_PHRASES)


def is_crisis_reply(text: str) -> bool:
    """这段「宠物要开口说的话」是不是危机 / 离线关怀话术。

    语音层（life/voice）拿它决定「要不要念出来」：这几段话术涉及隐私与情绪安全，
    该让人自己看、不该被机器大声念——尤其「拨打心理援助热线」那一句，念出来既冒失
    又不像样。文字照常显示，只有语音跳过（S4 危机拦截：危机句走危机话术最高优先，
    不播报）。
    """
    t = (text or "").strip()
    return t in (CRISIS_REPLY, SOFT_CARE_REPLY, SOFT_CARE_REPLY_DIVINATION)


def soft_care_reply(text: str, divination: bool = False) -> str:
    """模型不可用时的离线兜底：命中软表达就给本地关怀话术，否则返回空串。

    只用在"回话这一步失败/没钥匙"的分支上：硬表达走 is_crisis 那一道（永远不依赖模型），
    普通的话该报错就报错，只有这类"指向强但歧义大"的话才需要本地接一句。
    divination=True 时用玄机先生的口吻（内容一样，只是说法不同），保证玄学页里不混腔。
    """
    cleaned = _clean(text)
    if any(phrase in cleaned for phrase in SOFT_CRISIS_PHRASES):
        return SOFT_CARE_REPLY_DIVINATION if divination else SOFT_CARE_REPLY
    return ""

"""回话要贴着用户说的那句话（v2-chat-core #4 #5）：不引申、不编造。

用户真机反馈的两条，根子是同一个：

- **#4 自行引申**：用户说「今天天气真热，早知道不出门了」，回复里冒出"外面还有更累
  更烦的事吧"——用户只说了热，模型自己给它补了一层因果；
- **#5 编造用户的处境**：用户说丢了钱包，回复里冒出"我是不是太没用了"——这句用户
  压根没说，是模型替它造了一句心理活动，还当成用户的话来接。

两条回话路（`casual.py` 那条闲聊轻路、`counselor_lin.json` 那张角色卡的专业框架）
原先**一条约束都没有**管这件事（全仓搜过：回复链路零反编造条款，只有社交草稿
`templates.py` 里那一条，不在聊天链上）。所以这里单起一份，由
`PsychService._compose` 拼进提示，**两条路一起生效**。

为什么合成一个文件而不是各写一份：两条路各写一份，改一条忘一条，迟早分叉——用户
看到的就是"闲聊时好好的、一认真起来又开始编"。这里产出的只有文字，不改任何人设。
"""

from __future__ import annotations

# 硬约束。措辞都冲着"模型最容易滑出去的那几个动作"写，不是泛泛的"说实话"：
# 补因果、补心情、补没发生过的对话、把猜测写成事实——四个口子各堵一条。
RULES: tuple[str, ...] = (
    "【只说他说过的事】下面几条是硬约束，任何语气、任何情绪都不能松：",
    # 这里刻意写成「记忆里真记着的那些」而不是「上面那段」：这段提示词在两条回话路里
    # 都排在记忆段**前面**（见 persona_loader.messages / casual.messages 的顺序），
    # 说"上面"是错的；而且照抄记忆段的标题字会让别处的定位断言认错地方。
    "- 你只根据**用户这次说的那句话**，加上「记忆里真记着的那些」来回；别的你都不知道。",
    "- **不许替他补**他没说过的因果、处境、心情。他没说「累」，就不许说「你是不是很累」；"
    "他没说「没用」，就不许把这句安到他头上。",
    "- 他抱怨的**就是他说的那件事本身**（「真热」就是嫌热），顺着这件事接；"
    "别往「是不是还有别的事更烦」上引——那是你自己加的戏。",
    "- **不许编造你们之间没发生过的对话**（「你上次说…」「我们以前聊过…」）："
    "记忆里没记着的，就是没发生过。",
    "- 拿不准的地方**问他**，不要猜。猜出来的东西不许写成陈述句，只能写成问句"
    "（「你是不是有点…？」），而且一次只问一件事。",
)


def hint() -> str:
    """拼成要注入提示词的那一段。两条回话路都注同一份，一个字不差。"""
    return "\n".join(RULES)

"""邀约识别（v2-chat-core #7）：带时间词的邀请不是"要提醒"。

用户真机反馈：说「过两天请你吃饭」，宠物回一句

    「过两天」大概是几点呀？告诉我个时间，我到点喊你

——把一句邀约当成了登记日程。

根因链（都在这一条线上）：解析链把「过两天」判成模糊时间（fuzzy）→
`ChatterService._is_service_matter` 拦不住它（「吃饭」不在 config.card.categories
任何一个词表里；餐饮那栏只有外卖/油腻/奶茶/做饭/体重/泡面/夜宵）→ 整句落进
`AWAITING_TIME`，吐出 `ask_time_hint` 那句反问。

所以这里补一个判据：这句话是不是在**约**。是就不进等待态，走正常回话，
由 `INVITE_RULE` 交给模型去接这个邀请本身。
"""

from __future__ import annotations

# 邀约的说法。只收**足够明确**的那几种（请客 / 一起去 / 约个时间见面），
# 不收"晚点""改天聊聊"这类含糊的——那些本来就该按普通吐嘈走。
INVITE_WORDS: tuple[str, ...] = (
    "请你吃", "请你喝", "请你", "我请", "请客",
    "约饭", "约个饭", "约一下", "约个时间",
    "一起去", "一起吃饭", "一起喝", "一起玩", "一起聚", "一起看",
    "聚一聚", "聚聚", "要不要一起", "有空一起", "哪天一起", "什么时候一起",
    "带你去", "邀你", "赏脸",
)


def is_invitation(text: str) -> bool:
    """这句话是不是在约（纯词表，不调模型、不写库）。"""
    return any(word in text for word in INVITE_WORDS)


# 这一句是邀约时追加的那条。跟 grounding 一样，是提示词，不是行为开关——
# 拦不拦得住状态机由 is_invitation 管，说不说人话由这条管。
INVITE_RULE = (
    "【这一句是邀约，不是要你登记日程】他在约你（请客 / 一起去 / 约个时间见面）。"
    "接这个邀请本身——高兴、答应、或者说说自己那会儿的实际情况；"
    "**不要**追问「大概几点」这种把他当日程来登记的问题，也不要替他定时间。"
    "真想定的时候他自己会说。"
)

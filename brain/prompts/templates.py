# ---------- 说话者（v2-social-card-base） ----------
# 意图底座原先写死了"用户"：解析链 / 意图链的提示词里一律把这句话当成主人说的。
# 帮聊那条线上，被解读的那句话是**对方（聊天窗里的人）**说的，同一套意图判定换个主语
# 再用一次——所以这几个提示词里的"用户"提出来变成一格 `{speaker}`。
#
# 代号与称呼的对应表就这一份。**默认永远是 user**：老调用点一个都不传，取到的还是
# "用户"，拼出来的提示词与改动前**逐字相同**（这一点由测试钉住）。
SPEAKER_USER = "user"
SPEAKER_PEER = "peer"
SPEAKER_LABELS: dict[str, str] = {SPEAKER_USER: "用户", SPEAKER_PEER: "对方"}


def speaker_label(speaker: object) -> str:
    """说话者代号 → 提示词里的称呼。认不出的（空 / 别的词）一律按"用户"走。"""
    key = str(speaker or "").strip().lower()
    return SPEAKER_LABELS.get(key, SPEAKER_LABELS[SPEAKER_USER])



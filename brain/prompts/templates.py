def now_text(now: datetime | None = None) -> tuple[str, str]:
    """返回（'YYYY-MM-DD HH:MM'，星期几）。"""
    now = now or datetime.now()
    weekdays = ["星期一", "星期二", "星期三", "星期四", "星期五", "星期六", "星期日"]
    return now.strftime("%Y-%m-%d %H:%M"), weekdays[now.weekday()]
